# Every source file that can carry a comment starts with the SPDX line and the
# copyright line (KernGlobal rule "Headers"). Checks the first HEAD_LINES lines
# of each tracked or new, not-ignored file of a commentable kind. A shebang or
# a doctype may come first, hence more than two lines.

set -euo pipefail

cd "$(dirname "$0")/.."

HEAD_LINES=5
SPDX='SPDX-License-Identifier: AGPL-3.0-or-later'
COPYRIGHT='Copyright (c) 2026 Sricharan Suresh (github.com/verycareful)'

# Kinds that take a comment. Everything else (JSON, lockfiles, Markdown, images,
# VERSION, LICENSE, dot-config files) cannot carry the header or is not code,
# so it is not listed.
kinds='ts|tsx|js|mjs|css|rs|sh|py|yml|yaml|toml|html'

# Commentable files that are exempt, with the reason.
#   Cargo.lock       generated by cargo (a lockfile, not matched by kinds anyway)
#   src-tauri/gen/   generated by the Tauri build
#   dist/            build output
is_exempt() {
    case "$1" in
        src-tauri/gen/* | dist/* | */Cargo.lock) return 0 ;;
        *) return 1 ;;
    esac
}

status=0
while IFS= read -r f; do
    [[ -f $f ]] || continue
    is_exempt "$f" && continue
    head=$(head -n "$HEAD_LINES" -- "$f")
    for want in "$SPDX" "$COPYRIGHT"; do
        if ! grep -qF -- "$want" <<<"$head"; then
            echo "error: $f: no '$want' in the first $HEAD_LINES lines" >&2
            status=1
        fi
    done
done < <(git ls-files -co --exclude-standard | grep -E "\.($kinds)$" || true)

[[ $status -eq 0 ]] && echo "ok: every source file has its header"
exit "$status"
